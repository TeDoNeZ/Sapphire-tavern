const { chromium } = require('../.sharrowkin/qa/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const context=await browser.newContext({acceptDownloads:true});
 const page=await context.newPage();
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.argv[2]);
 await page.waitForSelector('#gallery-grid .hs-card');
 await page.getByRole('button',{name:'Существо',exact:true}).click();
 await page.locator('#minion-name').fill('Проверка стража');
 await page.locator('#minion-archetype').selectOption('Dragon');
 await page.locator('#minion-attack').fill('12');
 await page.locator('#minion-health').fill('24');
 await page.locator('[name="minion-tier"][value="8"]').check({force:true});
 for(const k of ['taunt','divineShield','poison','reborn','windfury','stealth']) await page.locator('[data-kw="'+k+'"]').check();
 await page.locator('#minion-token').check();
 await page.locator('[data-pick-image="minion"]').click();
 await page.getByRole('button',{name:'Коллекция image (3) 14',exact:true}).click();
 assert.equal(await page.locator('#picker-grid [role=option]').count(),14);
 await page.locator('#picker-grid [role=option]').first().click();
 assert.match(await page.locator('#picker-preview img').getAttribute('src'),/image/);
 await page.waitForFunction(()=>document.querySelector('#picker-preview img').naturalWidth>0);
 await page.locator('#picker-apply').click();
 await page.locator('#minion-form [type=submit]').click();
 await page.getByRole('button',{name:'Заклинание',exact:true}).click();
 await page.locator('#spell-name').fill('Проверка заклинания');
 await page.locator('#spell-cost').fill('7');
 await page.locator('[name="spell-tier"][value="7"]').check({force:true});
 await page.locator('#spell-description').fill('Дайте существу +7/+7.');
 await page.locator('#spell-form [type=submit]').click();
 const downloadPromise=page.waitForEvent('download');
 await page.locator('#export-btn').click();
 const download=await downloadPromise;
 const downloaded=await download.path();
 const payload=JSON.parse(fs.readFileSync(downloaded,'utf8'));
 const minion=payload.minions.find(x=>x.name==='Проверка стража');
 assert.equal(minion.tier,8); assert.equal(minion.attack,12); assert.equal(minion.health,24);
 assert.equal(minion.archetype,'Dragon'); assert(minion.isToken); assert(Object.values(minion.keywords).every(Boolean));
 assert.equal(payload.spells.find(x=>x.name==='Проверка заклинания').cost,7);
 await page.evaluate(()=>localStorage.clear()); await page.reload();
 page.on('dialog',d=>d.accept());
 await page.locator('#import-input').setInputFiles(downloaded);
 await page.waitForFunction(()=>document.querySelector('#gallery-grid').textContent.includes('Проверка стража'));
 await page.locator('#filter-type').selectOption('spell');
 assert.equal(await page.locator('#gallery-grid .hs-card').count(),payload.spells.length);
 await page.getByRole('button',{name:'Таверна 7',exact:true}).click();
 assert.equal(await page.locator('#gallery-grid .hs-card').count(),1);
 await page.locator('#filter-reset').click();
 await page.locator('#filter-archetype').selectOption('Dragon');
 assert.equal(await page.locator('#gallery-grid .hs-card').count(),1);
 await page.locator('#filter-reset').click();
 for(let t=1;t<=8;t++) {
   await page.getByRole('button',{name:'Таверна '+t,exact:true}).click();
   const tiers=await page.locator('#gallery-grid .hs-card').evaluateAll(els=>els.map(e=>Number(e.dataset.tier)));
   assert(tiers.every(x=>x===t));
 }
 await page.locator('#filter-reset').click();
 await page.locator('input[name=viewMode][value=mobile]').check({force:true});
 await page.setViewportSize({width:390,height:844});
 assert(await page.locator('body').evaluate(e=>e.classList.contains('mobile-mode')));
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.getByRole('button',{name:'Существо',exact:true}).click();
 assert.equal(await page.locator('.editor-layout').first().evaluate(e=>getComputedStyle(e).gridTemplateColumns.split(' ').length),1);
 await page.locator('input[name=viewMode][value=desktop]').check({force:true});
 assert(await page.locator('body').evaluate(e=>e.classList.contains('desktop-mode')));
 assert.deepEqual(errors,[]);
 await browser.close();
 console.log('PASS: create minion/spell, all keywords, image folders/live preview, real download/upload JSON round-trip, type/archetype/tiers 1-8 filters, manual modes, 390px layout; no JS errors.');
})().catch(e=>{console.error(e);process.exit(1)});
