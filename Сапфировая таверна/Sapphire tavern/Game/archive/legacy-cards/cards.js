export const cardById = Object.fromEntries([...cards, ...tokens].map(c => [c.id, c]));

let serial = 0;
export function makeUnit(id, rank = 1) {
  const c = cardById[id];
  if (!c) throw new RangeError(`Unknown card: ${id}`);
  if (![1, 2, 4].includes(rank)) throw new RangeError('Rank must be 1, 2 or 4');
  return {...c, uid:`unit-${Date.now().toString(36)}-${++serial}`, rank, attack:c.attack*rank, health:c.health*rank, maxHealth:c.health*rank, keywords:[...(c.keywords || [])], gifts:[]};
}

export const isTribe = (unit, tribe) => {
  if (!unit) return false;
  const memberships = unit.tribes || (unit.tribe || '').split('/');
  return memberships.includes(tribe);
};
export const canMagnetize = (unit, target) => !!unit && (unit.keywords || []).includes('magnetic') && (isTribe(target, 'mech') || (unit.id === 'u31' && isTribe(target, 'undead')));
